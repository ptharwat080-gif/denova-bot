  return `${header}
العيادة فاتحة وبتستقبل حجوزات وزيارات عادي. عروض يوم الافتتاح الثلاثة خلصت خالص ومبقتش متاحة. لو حد سأل عنها، قوله بلطف إنها كانت لفترة محدودة وخلصت دلوقتي، واعرض عليه بدلها حجز كشف عادي مع تسعير بيتحدد بعد الكشف. ممنوع تمامًا تعرض أسعار العروض القديمة أو توحي إنها لسه شغالة.`;
